"""한국어_tsquery 는 순수 함수라 DB 없이 검사한다.

DB 통합 테스트에서는 간접적으로만 거쳐가서, 토큰화 규칙 자체를
직접 단언하는 곳이 없었다(reviewer 지적).
"""

from adapters.db.chunk_search import 한국어_tsquery


def test_자연어_문장을_접두어_OR_tsquery로_바꾼다():
    # 조사와 어미가 붙어도 접두어 매칭이 흡수하도록 :* 를 붙이고 | 로 잇는다.
    assert 한국어_tsquery("이상행위 모니터링은 어떻게 하나요?") == (
        "이상행위:* | 모니터링은:* | 어떻게:* | 하나요:*"
    )


def test_낱말이_없으면_빈_문자열이다():
    # 문장부호만 있으면 _낱말 정규식에 걸리는 게 없다.
    assert 한국어_tsquery("...?!") == ""


def test_한_글자_토큰은_버려진다():
    # len(w) >= 2 조건 — 한 글자는 노이즈일 가능성이 높다.
    assert 한국어_tsquery("이 것 은 예시") == "예시:*"


def test_조항_코드는_한_덩어리로_남는다():
    # simple 파서도 '2.11.3' 을 한 토큰으로 본다 — _낱말 정규식이 점을
    # 낱말 문자로 취급해 쪼개지 않는다.
    assert 한국어_tsquery("2.11.3 조항을 알려줘") == "2.11.3:* | 조항을:* | 알려줘:*"


def test_tsquery_메타문자는_제거된다():
    # 사용자 입력을 그대로 to_tsquery 에 넘기면 &|!():* 가 tsquery 문법으로
    # 해석되어 구문 오류가 난다. _낱말 이 그 글자들을 전부 걸러낸다.
    assert 한국어_tsquery("접근 & 통제 | 없음 ! (테스트) :*") == (
        "접근:* | 통제:* | 없음:* | 테스트:*"
    )
