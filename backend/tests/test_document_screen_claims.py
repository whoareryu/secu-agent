"""문서 화면 둘이 서로 다른 말을 하는데, 둘 다 참이어야 한다.

`/my/documents` 는 화면에 이렇게 적는다:

    걸러내기는 서버에서 끝납니다 — 목록에 없는 문서는 제목조차 브라우저에
    오지 않습니다.

`(explain)/documents` 는 정반대로 한다 — 권한 필터 없는 전체 카탈로그를
브라우저로 받아, 못 보는 행을 "가려짐" 배지로 그린다. 그래야 규칙을 밖에서
보여주는 화면이 성립한다.

**둘 다 참이다.** 앞의 문장이 참인 이유는 그 화면이 서버 컴포넌트라서
`visible()` 로 거른 뒤의 목록만 마크업에 담기기 때문이고, 뒤의 화면이
그래도 되는 이유는 이 코퍼스가 합성이고 `data/policies/` 에 공개돼 있기
때문이다(문서 본문에 `clearance: 3` 까지 적힌 채로 커밋돼 있다).

**그런데 앞의 문장은 구현 사실 하나에만 매달려 있다.** 누가
`my/documents/page.tsx` 에 `"use client"` 를 붙이고 `/api/documents` 를
부르면, 코드는 잘 돌고 화면은 똑같아 보이는데 그 문장만 조용히 거짓이 된다.
전체 카탈로그가 브라우저로 내려가기 때문이다.

그런 문장은 테스트로 붙잡는다 — tests/test_how_screen_claims.py 가 /how 의
전수 주장에 하는 것과 같은 일이다.
"""

import re
from pathlib import Path

import pytest

# CWD 에 기대지 않는다. pytest 를 어디서 부르든 같은 파일을 봐야 한다
# (adapters/db/connection.py 가 schema.sql 을 푸는 방식과 같다).
_저장소 = Path(__file__).resolve().parents[2]
_직원_면 = _저장소 / "frontend" / "app" / "(employee)"
_내_문서 = _직원_면 / "my" / "documents" / "page.tsx"
_설명_문서 = _저장소 / "frontend" / "app" / "(explain)" / "documents" / "page.tsx"

# 브라우저에서 부르는 무필터 카탈로그 경로. 백엔드 GET /documents 를 그대로
# 중계하므로 이것을 부르는 클라이언트 코드는 전체 목록을 받는다.
_무필터_카탈로그 = "/api/documents"


def test_검사할_화면이_있다():
    """경로가 틀리면 아래 테스트들이 공허하게 통과한다."""
    assert _내_문서.exists(), f"{_내_문서} 가 없다"
    assert _설명_문서.exists(), f"{_설명_문서} 가 없다"
    assert _직원_면.is_dir(), f"{_직원_면} 가 없다"


def test_내_문서_화면은_서버_컴포넌트다():
    """이 화면의 "제목조차 브라우저에 오지 않습니다" 가 참인 이유가 이것뿐이다.

    서버 컴포넌트라 `visible()` 로 거른 뒤의 목록만 마크업에 담긴다.
    `"use client"` 가 붙으면 데이터를 브라우저에서 받게 되고, 그 순간
    화면의 문장이 거짓이 된다 — 화면 모양은 그대로라 눈으로는 안 보인다.
    """
    본문 = _내_문서.read_text(encoding="utf-8")
    # 따옴표 종류를 가리지 않는다. 이 저장소에는 prettier·eslint 설정이 없어
    # 두 표기가 다 들어올 수 있다.
    assert not re.search(r"""^\s*['\"]use client['\"]""", 본문, re.MULTILINE), (
        '내 문서 화면에 "use client" 가 붙었다. 서버에서 걸러야 '
        "'목록에 없는 문서는 제목조차 브라우저에 오지 않습니다' 가 참이다 — "
        "화면 문장도 같이 고칠 것인지 확인하라."
    )


_공유_컴포넌트 = _저장소 / "frontend" / "components"

# my/documents 가 무필터 목록을 담는 지역 변수. 이것이 JSX 로 흘러 나가면
# 서버 컴포넌트인 채로도 RSC 페이로드에 직렬화돼 브라우저로 내려간다.
#
# JSX 표현식 중괄호 **안 어디든** 그 이름이 있으면 잡는다. 첫 판은
# `={문서}` · `{문서.` · `{문서}` 세 모양만 봐서 `={ 문서 }`(공백 하나)와
# `{...{ all: 문서 }}`(전개)가 그냥 통과했다.
#
# **여는 중괄호와 같은 줄**에 그 이름이 오는 것만 본다. 닫는 중괄호까지
# 요구하면 `{문서.map((d) => (` 처럼 여러 줄로 이어지는 가장 흔한 모양을
# 놓치고, 줄바꿈을 허용하면 데이터를 가져오는 `try { … }` 블록이 오탐으로
# 걸린다. 이 한 줄이 그 사이다.
_무필터_변수가_JSX_로 = re.compile(r"\{[^{}\n]*\b문서\b")

# 걸러내는 줄의 **모양**을 고정한다. `visible(` 토큰 존재만 보면
# `문서.filter((d) => visible(d, me) || true)` 나 `문서.map((d) => d)` 로
# 필터를 무력화해도 통과한다 — 죽은 참조 한 줄로도 만족되기 때문이다.
_거르는_줄 = "const 보이는것 = 문서.filter((d) => visible(d, me));"


def _tsx_파일들(뿌리: Path) -> list[Path]:
    return sorted(뿌리.rglob("*.tsx")) + sorted(뿌리.rglob("*.ts"))


def test_내_문서_화면이_무필터_목록을_JSX_로_넘기지_않는다():
    """서버 컴포넌트인 것만으로는 부족하다.

    `"use client"` 가 없어도 무필터 배열을 클라이언트 컴포넌트의 prop 으로
    넘기면 RSC 페이로드에 직렬화돼 브라우저로 내려간다 — 화면 모양은
    똑같은데 "제목조차 오지 않습니다" 만 거짓이 된다.

    이 파일은 `문서`(무필터)와 `보이는것`(visible() 통과분) 두 이름을 쓴다.
    렌더에 들어가도 되는 것은 뒤쪽뿐이다.

    **이 그물이 잡지 못하는 것이 하나 있다.** `const 별칭 = 문서;` 처럼 이름을
    갈아 끼우면 문자열 검사로는 따라갈 수 없다 — 그러려면 데이터 흐름을 봐야
    하고 그건 이 파일의 방식이 아니다. 화면 문장은 이 한계를 넘어서 말하지
    않는다("가장 흔한 모양까지 잡습니다").
    """
    본문 = _내_문서.read_text(encoding="utf-8")
    assert _거르는_줄 in 본문, (
        f"걸러내는 줄이 이 모양이 아니다: {_거르는_줄!r}. 모양을 바꿔야 한다면 "
        "화면 문장이 여전히 참인지 같이 확인하라."
    )
    새는_자리 = _무필터_변수가_JSX_로.findall(본문)
    assert 새는_자리 == [], (
        f"무필터 목록이 JSX 로 흘러간다: {새는_자리}. 서버 컴포넌트라도 prop 은 "
        "직렬화되어 브라우저로 내려간다 — 렌더에는 보이는것 만 넣는다."
    )


def test_직원_면_어디에서도_무필터_카탈로그를_브라우저로_부르지_않는다():
    """직원 면 전체에 거는 그물이다.

    위 테스트는 파일 하나만 본다. 직원 면에 화면이 하나 더 생기고 그쪽이
    /api/documents 를 부르면 같은 문제가 다른 자리에서 재현된다.

    부분집합이 아니라 **부재**로 고정한다 — 여기 이름을 올릴 수 있는 예외가
    지금은 없고, 생긴다면 그건 화면 문장을 다시 볼 이유이지 목록에 한 줄
    더할 이유가 아니다.

    설명 면(`(explain)/documents`)은 이 그물 밖이다. 그쪽이 무필터로 받는
    것이 이 프로젝트의 의도이고, 화면이 그 사실을 직접 적는다(아래 테스트).
    """
    # 직원 면만 훑으면 그물이 얕다. 직원 화면이 그리는 컴포넌트는 전부
    # frontend/components/ 에 있고, 그쪽에서 부르면 같은 일이 일어난다.
    부르는_파일 = [
        str(p.relative_to(_저장소))
        for p in _tsx_파일들(_직원_면) + _tsx_파일들(_공유_컴포넌트)
        if _무필터_카탈로그 in p.read_text(encoding="utf-8")
    ]
    assert 부르는_파일 == [], (
        f"직원 면이 무필터 카탈로그({_무필터_카탈로그})를 브라우저에서 부른다: {부르는_파일}. "
        "전체 목록이 브라우저로 내려가므로 '제목조차 오지 않습니다' 가 깨진다."
    )


def _주석_제거(소스: str) -> str:
    """`//` 줄 주석과 `/* */` 블록 주석을 지운다.

    **이 함수가 이 파일의 요점이다.** 아래 테스트는 "화면이 무엇을 말하는가"를
    보는데, 주석까지 세면 코드 주석 한 줄로 통과해버린다. 실제로 첫 판이
    그랬다 — `권한 필터 없이` 가 9행 주석에만 있는데 테스트가 초록불이었다.
    화면을 읽는 사람에게 주석은 존재하지 않는다.

    **줄 앞 주석만 지우면 안 된다.** 첫 판이 `^\\s*//` 였고, 그래서 코드 뒤에
    붙은 `const a = 1;  // 권한 필터 없이` 한 줄로 통과했다 — 화면 문단을
    통째로 지워도 초록불이었다. 이 파일이 존재하는 유일한 이유를 그대로
    비켜간 것이다.

    문자열 리터럴 안의 `//`(URL 등)와 `"/*"` 같은 리터럴까지 정교하게
    가리지는 않는다. 둘 다 **엄격해지는**(있는 문장을 못 봤다고 실패하는)
    방향이라 공허한 통과를 만들지 않는다. 이 파일이 보는 것은 한국어
    문장이고, 그 문장이 주석이 아닌 자리에 있는지만 가리면 충분하다.
    """
    소스 = re.sub(r"/\*.*?\*/", " ", 소스, flags=re.DOTALL)
    return re.sub(r"//[^\n]*", " ", 소스)


def test_주석은_화면_문장으로_세지_않는다():
    """위 함수가 망가지면 아래 두 테스트가 조용히 공허해진다."""
    assert "지워진다" not in _주석_제거("// 지워진다\nconst a = 1;")
    # 첫 판이 놓친 자리다. 이 줄이 없으면 화면 문단을 지우고 주석 한 줄만
    # 남겨도 통과한다.
    assert "지워진다" not in _주석_제거("const a = 1;  // 지워진다")
    assert "지워진다" not in _주석_제거("/* 여러 줄\n   지워진다 */\nconst a = 1;")
    assert "지워진다" not in _주석_제거("{/* JSX 주석에서도 지워진다 */}")
    assert "남는다" in _주석_제거("// 지워진다\n<p>남는다</p>")


@pytest.mark.parametrize(
    "표지",
    [
        # 이 화면이 **의도적으로** 무필터라는 것을 화면 자신이 말해야 한다.
        # 코드 주석에만 있으면 화면을 읽는 사람은 두 화면이 모순이라고 읽는다.
        "권한 필터 없이",
        # 그래도 되는 이유 — 코퍼스가 합성이고 저장소에 공개돼 있다.
        #
        # "합성" 두 글자를 쓰면 안 된다. 이 변경 **이전** 문장에도 그 낱말이
        # 있어서 마커가 아무것도 고정하지 못했다(HEAD 판으로 되돌려도
        # 이 케이스만 통과했다). 새 문단에만 있는 구절을 쓴다.
        "공개 저장소",
    ],
)
def test_설명_문서_화면이_스스로_예외임을_밝힌다(표지: str):
    본문 = _주석_제거(_설명_문서.read_text(encoding="utf-8"))
    assert 표지 in 본문, (
        f"설명 면 문서 화면의 **화면 문장**에 '{표지}' 가 없다(주석은 세지 않는다). "
        "이 화면은 전체 카탈로그를 브라우저로 받는 유일한 자리이고, 그 사실을 "
        "화면이 직접 말하지 않으면 내 문서 화면의 문장과 모순으로 읽힌다."
    )
