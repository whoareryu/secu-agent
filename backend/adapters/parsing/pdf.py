"""PDF → 조항 → 청크.

ISMS-P 안내서는 "2.6.1 네트워크 접근" 형태로 조항 코드가 줄 앞에 온다.
조항 경계를 먼저 잡고 그 안에서 청킹하는 이유: 경계를 무시하고 고정 길이로
자르면 한 청크가 두 조항에 걸치고, 리포트에서 잘못된 조항을 인용하게 된다.

이 모듈은 문서 포맷만 안다 — DB 도 임베딩도 모른다.
"""

import re
from pathlib import Path

from pypdf import PdfReader

from adapters.parsing.chunking import chunk_clauses
from core.types import Clause

# "1.3.1 보호대책 구현" — 줄 앞의 조항 코드와 제목.
#
# 각 자리는 반드시 \d+ 다. \d 로 쓰면 2.10·2.11·2.12 가 구조적으로 매치되지
# 않는다 — 실측에서 그 16개(2.10.1~2.12.2)를 통째로 잃었다. 그 안에는
# "2.11.3 이상행위 분석 및 모니터링" 처럼 이 프로젝트의 핵심 조항이 들어 있다.
# 실측: 255쪽 전문에서 고유 조항 102개 — ISMS-P 2022 공식 인증기준 수와 일치한다.
# 제목 길이 상한. 넘으면 그 줄이 조항으로 안 잡히고, **조항 전체가 앞
# 조항의 본문으로 삼켜지면서 조항 코드가 사라진다** — 에러 없이 데이터가
# 없어지는 경로다. 상한 자체는 필요하다(본문 한 줄이 우연히 "2.6.1 " 로
# 시작할 때 조항으로 오인하는 것을 막는다). 실측으로 여유를 넓혔다: 지금
# 코퍼스의 최장 제목은 21자이고, 200 으로 올려도 조항 102개·청크 314개가
# 그대로다.
_제목_최대 = 200
조항_패턴 = re.compile(rf"^\s*(\d+\.\d+\.\d+)\s+(\S[^\n]{{0,{_제목_최대}}})$", re.MULTILINE)

# 마지막 조항(3.5.3) 뒤에 붙는 참고문헌 목록의 시작 표지.
# ISMS-P 안내서 실물(인쇄본 기준 약 250쪽)의 후주에서 실측으로 확인한
# 값이다 — 일반적인 규칙이 아니라 이 문서에 한정된 값이므로, 다른
# 안내서나 개정판에서는 다시 확인해야 한다. 이 표지가 없으면(픽스처처럼
# 후주가 없는 텍스트) 마지막 조항은 지금처럼 문서 끝까지 이어진다.
참고자료_표지 = "참고자료"


# 사설 사용 영역(Private Use Area). 유니코드가 의미를 정하지 않는 구간이라
# 폰트마다 다른 글자가 되고, 그 폰트가 없으면 아무것도 아니다.
#
# ISMS-P 안내서는 불릿을 Wingdings 계열 심볼 폰트로 찍었고, pypdf 는 그것을
# 매핑 없이 원래 코드포인트 그대로 뽑는다. 실측(2026-09-04, 작업 코퍼스):
# 338 청크 중 310 개에 2,062 자 — U+F09F 1,666 · U+F06E 378 · U+F0AB 9 ·
# U+F020 9. 이것이 셋 모두를 오염시켰다:
#   화면    브라우저에 폰트가 없어 tofu 박스로 그려진다(문서 사이트의
#           ask-answer.png 에도 그대로 찍혀 있다)
#   LLM     의미 없는 토큰 수천 개가 프롬프트에 들어간다
#   검색    tsvector 와 임베딩에 잡음으로 남는다
#
# U+F020 은 심볼 폰트의 **공백**이라 공백으로 돌려놓고, 나머지는 불릿이므로
# 가운뎃점으로 정규화한다. 지우지 않는 이유는 목록 항목의 경계를 남기기
# 위해서이고, 길이가 1:1 이라 청크 경계가 움직이지 않기 때문이다.
#
# **네 가지를 실측하고 골랐다**(골든셋 30건 · k=10):
#   유지        338청크  Recall .867  MRR .577  nDCG .644
#   → 가운뎃점  338청크  Recall .867  MRR .526  nDCG .607   ← 채택
#   → 공백      338청크  Recall .833  MRR .553  nDCG .619
#   → 제거      337청크  Recall .867  MRR .531  nDCG .612
# 정리하면 어느 쪽이든 MRR·nDCG 가 내려간다. 길이가 같은 두 변형에서도
# 내려가므로 청크 경계 이동이 아니라 토크나이제이션 차이다 — PUA 는 e5
# 토크나이저에서 미지 토큰이 되고, 그 자리에 실제 토큰이 들어가면 문서
# 벡터가 움직인다. 순위가 흔들릴 뿐 **Recall 은 그대로**여서, 정답 문서를
# 못 찾게 된 것이 아니라 같은 문서들의 순서가 바뀐 것이다.
# 가운뎃점을 고른 근거: Recall 을 지키는 두 후보(가운뎃점·제거) 중 청크 수
# 338 을 유지하는 쪽이다 — 코드 주석·테스트·문서 사이트가 그 숫자를 인용한다.
#
# 조항 분할보다 **먼저** 적용한다. 실측으로 조항 102개 · 청크 314개가 그대로
# 유지되고 코드·제목 집합도 동일함을 확인했다(test_pdf_parsing.py).
_PUA = re.compile(r"[-]")
_PUA_공백 = ""


def 사설영역_정리(text: str) -> str:
    """PUA 글리프를 사람이 읽을 수 있는 것으로 바꾼다."""
    return _PUA.sub("·", text.replace(_PUA_공백, " "))


def extract_text(path: Path) -> str:
    reader = PdfReader(str(path))
    본문 = "\n".join((page.extract_text() or "") for page in reader.pages)
    return 사설영역_정리(본문)


def split_clauses(text: str) -> list[Clause]:
    """조항 코드로 텍스트를 분할한다.

    조항 앞의 머리말(표지·목차)은 버린다 — 조항이 아니고, 검색되면
    "규정 어디에 있다"고 말할 수 없다.

    각 조항 코드는 목차와 본문에 각각 한 번씩 등장한다(실측: 204회 = 고유
    102개 x 2, 예외 없음). 같은 코드가 두 번 잡히면 본문이 더 긴 쪽을 채택한다 —
    목차 항목은 다음 목차 줄이 바로 뒤따라 본문이 극히 짧게 잘리기
    때문이다. 순서는 최초 등장 순서를 유지한다.
    """
    matches = list(조항_패턴.finditer(text))
    by_code: dict[str, Clause] = {}
    order: list[str] = []
    for i, m in enumerate(matches):
        시작 = m.end()
        if i + 1 < len(matches):
            끝 = matches[i + 1].start()
        else:
            # 마지막 조항은 다음 조항 코드가 없어 원래 문서 끝까지 이어진다.
            # 그런데 ISMS-P 안내서는 마지막 조항(3.5.3) 바로 뒤에 참고문헌
            # 목록이 붙어 있어, 표지를 찾지 못하면 그 목록까지 본문으로
            # 삼켜버린다. 표지가 있으면 거기서 끊고, 없으면(픽스처처럼
            # 후주가 없는 텍스트) 지금까지처럼 문서 끝까지 쓴다.
            표지_위치 = text.find(참고자료_표지, 시작)
            끝 = 표지_위치 if 표지_위치 != -1 else len(text)
        본문 = text[시작:끝].strip()
        code = m.group(1)
        clause = Clause(code=code, title=m.group(2).strip(), text=본문)
        기존 = by_code.get(code)
        if 기존 is None:
            order.append(code)
            by_code[code] = clause
        elif len(clause.text) > len(기존.text):
            by_code[code] = clause
    return [by_code[code] for code in order]


