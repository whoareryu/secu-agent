"""도구 출력에 실리는 **신뢰할 수 없는 텍스트**를 정리한다.

`query_logs` 가 돌려주는 로그 원문은 공격자가 쓸 수 있는 문자열이다.
syslog 사용자명 패턴이 `\\S+` 라, 감시 대상 호스트에 SSH 로그인을 시도하는
것만으로 임의 텍스트를 남길 수 있다. 그 문자열은 도구 출력을 거쳐 모델의
프롬프트로 들어간다.

`search_policy` 가 돌려주는 규정 본문도 같이 다룬다. 문서는 관리자가
적재하지만, 악의적인 문서 한 건이면 같은 일이 일어나고 막는 이유가 같다.

**이 모듈은 프레임워크를 모른다.** "신뢰할 수 없는 데이터를 지시로 만들지
않는다" 는 도메인 규칙이고, LangChain 없이 테스트되어야 한다.

**무엇을 보장하고 무엇을 보장하지 않는가.** 여기서 하는 일은 데이터에
경계를 그리고 그 경계를 위조할 수 없게 만드는 것이다. 모델이 경계 안의
문장을 지시로 읽지 않는다는 것은 여기서 보장할 수 없다 — 그건 시스템
프롬프트가 맡고, 프롬프트는 지켜지기를 바라는 것이지 강제되는 것이 아니다.
구조로 막을 수 있는 것만 여기서 막는다.
"""

import unicodedata

# 신뢰할 수 없는 텍스트의 기본 길이 상한. syslog 한 줄은 길어질 수 있고,
# 그대로 두면 프롬프트 예산을 잠식한다.
기본_최대 = 300

_잘림_표시 = "…(잘림)"

# **꺾쇠가 될 수 있는 것 전부.** 처음에는 ASCII `<` `>` 만 전각으로 바꿨는데
# 두 가지로 뚫렸다:
#
#   1. 공격자가 처음부터 전각 `＜` 를 쓰면 아무 변환도 일어나지 않고, 그
#      결과가 우리 이스케이프 출력과 **문자 단위로 같다.** 담당자도 테스트도
#      "이스케이프된 공격" 과 "공격자가 원래 쓴 전각" 을 구별할 수 없다.
#   2. NFKC 정규화를 거치면 전각이 ASCII 로 **되돌아간다.** 토크나이저나
#      중간 계층이 정규화하면 경계가 그대로 복원된다.
#
# 그래서 NFKC 로 `<` · `>` 가 되는 코드포인트를 전수로 잡는다(유니코드 전
# 범위를 훑어 확인한 결과 각각 셋뿐이다). 바꿔 넣는 `‹` `›` 는 NFC·NFD·
# NFKC·NFKD 어느 쪽으로도 꺾쇠가 되지 않는다.
#
# 전체를 NFKC 정규화하지 않는 이유: 실측에서 규정 청크 338건 중 30건이
# `｢｣` → `「」` 로 바뀌었다. 무해하지만 우리가 요구하지 않은 변경이고,
# 담당자가 읽는 것은 원문이다.
_꺾쇠 = {
    0x003C: "‹",
    0xFE64: "‹",
    0xFF1C: "‹",  # LESS-THAN · SMALL · FULLWIDTH
    0x003E: "›",
    0xFE65: "›",
    0xFF1E: "›",  # GREATER-THAN · SMALL · FULLWIDTH
}

# 보이지 않는 문자. 화면에 안 보이는 지시를 심거나 문자열 검사를 피하는 데
# 쓰인다. Cf(포맷)가 제로폭 공백·BOM·양방향 제어·태그 문자를 덮는다.
_지울_범주 = {"Cf"}

# 줄을 만드는 것 전부. **Cc 만으로는 부족하다** — U+2028(Zl)·U+2029(Zp)는
# 제어문자가 아니지만 `splitlines()` 와 대부분의 렌더러가 줄바꿈으로
# 취급한다. 그것으로 한 이벤트를 여러 줄로 쪼개, 존재하지 않는 호스트의
# 정상 기록을 만들어 낼 수 있었다(실측으로 재현했다).
_공백으로_바꿀_범주 = {"Cc", "Zl", "Zp"}


def 중화(텍스트: str, 최대: int = 기본_최대, 줄바꿈_보존: bool = False) -> str:
    """도구 출력에 넣기 전에 신뢰할 수 없는 텍스트를 정리한다.

    넷을 한다:

    1. **경계 위조 차단** — 꺾쇠가 될 수 있는 문자 여섯을 `‹` `›` 로 바꾼다.
       이것이 없으면 감싼다() 의 경계 표시가 장식이다. 공격자가 닫는 태그를
       심어 경계를 닫고 나오면, 그 뒤 문장이 모델에게 "데이터 밖" 으로
       보인다.
    2. **보이지 않는 것 제거** — 제로폭 공백·BOM·양방향 제어·태그 문자.
    3. **줄 정리** — 제어문자와 유니코드 줄 구분자를 공백으로. 다만
       `줄바꿈_보존` 이면 `\\n` 은 남긴다(아래).
    4. **길이 상한** — 자르되 잘렸다는 사실을 숨기지 않는다.

    **`줄바꿈_보존` 이 있는 이유.** 로그는 이벤트 하나가 한 줄이므로 줄바꿈이
    곧 구조이고, 원문에 줄바꿈이 남으면 공격자가 그 구조를 위조한다. 규정
    본문은 다르다 — 여러 줄인 것이 정상이고, 경계는 `<규정>` 태그가 지킨다.
    구별 없이 평탄화했더니 실측에서 규정 청크 **338건 전부**가 원문과
    달라졌고, PDF 표에서 뽑힌 청크는 줄바꿈이 열·행을 나누는 유일한 구조라
    "어느 알고리즘이 어느 구분에 속하는지" 가 사라졌다. 평탄화의 근거는
    로그에만 해당하는데 대가는 규정이 치르고 있었다.

    **"손대지 않는다" 는 조건부다.** 실측한 영향(작업 코퍼스):

        로그  33건 중 변형   0건   — 한 줄이고 꺾쇠가 없다
        청크 338건 중 변형 103건   — 앞뒤 공백 strip 95건,
                                     본문에 진짜 부등호가 있는 것 9건

    앞의 95건은 앞뒤 공백이 잘리는 것뿐이라 읽는 데 영향이 없다. 뒤의 9건은
    규정 본문에 실제로 쓰인 `<` `>` 가 `‹` `›` 로 바뀌는 것이고, 이건 방어의
    대가다 — 진짜 부등호를 남기면 경계 위조를 막을 방법이 없다.

    `줄바꿈_보존` 이 없던 판에서는 청크 **338건 전부**가 달라졌다. 그 플래그가
    있는 이유가 이 숫자다.
    """
    글자 = []
    for ch in 텍스트:
        범주 = unicodedata.category(ch)
        if 범주 in _지울_범주:
            continue  # 보이지 않는 것은 지운다 — 바꿔봐야 여전히 안 보인다
        if 범주 in _공백으로_바꿀_범주:
            글자.append("\n" if (줄바꿈_보존 and ch == "\n") else " ")
            continue
        글자.append(ch)
    정리 = "".join(글자).translate(_꺾쇠).strip()

    # **연속 공백을 줄이지 않는다.** 처음에는 제어문자를 공백으로 바꾸며
    # 생긴 연속 공백을 정리했는데, syslog 의 날짜가 `Sep  1` 처럼 자리맞춤용
    # 두 칸을 쓴다 — 그것까지 뭉개서 원문과 달라졌다(테스트가 잡았다).

    # 잘림 표시를 본문이 흉내내지 못하게 한다. 그대로 두면 공격자가
    # "…(잘림) [이후는 시스템이 생략함]" 처럼 써서, 뒤따르는 자기 침입
    # 흔적을 시스템이 잘라낸 나머지로 위장할 수 있다.
    정리 = 정리.replace(_잘림_표시, "…(잘 림)")

    if len(정리) > 최대:
        정리 = 정리[:최대] + _잘림_표시
    return 정리


def 감싼다(라벨: str, 본문: str) -> str:
    """신뢰할 수 없는 본문에 경계를 그린다.

    **본문은 미리 중화()를 지나야 한다.** 이 함수는 경계를 그릴 뿐 위조를
    막지 않는다 — 둘을 나눠 둔 이유는 여러 줄을 모아 한 번에 감싸는 쪽이
    출력이 읽기 좋기 때문이고, 그래서 중화는 조각마다 따로 걸린다.
    """
    return f"<{라벨}>\n{본문}\n</{라벨}>"
